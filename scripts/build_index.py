"""Build index/ from the case headers, then run tests/search-cases.tsv.

Never edit the generated files by hand. index/synonyms.json is hand maintained.
Prints INDEX_OK <cases> and TESTS_OK <n>, or FORMAT_ERROR / TEST_FAILED lines and exits 1.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from normalize import normalize, normalize_error, phrase_list  # noqa: E402
import kbsearch  # noqa: E402

ROOT = os.path.dirname(HERE)
CASES = os.path.join(ROOT, "cases")
INDEX = os.path.join(ROOT, "index")
TYPES = ["app", "web", "addon", "integration", "account"]
FIELDS = ["title", "type", "fix", "error", "keywords"]
FIX = ["confirmed", "unconfirmed"]
HEADINGS = ["## Debugging steps", "## Solution", "## Customer note"]
NAME_RE = re.compile(r"^(\d{3,})(-\d+)?\.md$")


def parse_case(path, folder, name):
    """Return (case id, header dict) or raise ValueError with a short reason."""
    m = NAME_RE.match(name)
    if not m:
        raise ValueError("bad file name")
    if m.group(1)[:-2] != folder:
        raise ValueError("wrong folder")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    lines = text.split("\n")
    if lines[0].strip() != "---":
        raise ValueError("no header")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise ValueError("header not closed")
    header = {}
    keys = []
    for line in lines[1:end]:
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError("bad header line")
        keys.append(key.strip())
        header[key.strip()] = value.strip()
    if keys != FIELDS:
        raise ValueError("header fields must be exactly " + ", ".join(FIELDS))
    if not header["title"]:
        raise ValueError("empty title")
    if header["type"] not in TYPES:
        raise ValueError("bad type")
    if header["fix"] not in FIX:
        raise ValueError("fix must be confirmed or unconfirmed")
    if not header["keywords"]:
        raise ValueError("empty keywords")
    headings = []
    in_code = False
    for l in lines[end + 1:]:
        if l.lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code and l.startswith("#"):
            headings.append(l.rstrip())
    if headings != HEADINGS:
        raise ValueError("headings must be exactly Debugging steps, Solution, Customer note")
    return "%s/%s" % (folder, name[:-3]), header


def write_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=0, sort_keys=True)
        f.write("\n")


def clear_generated(sub):
    d = os.path.join(INDEX, sub)
    os.makedirs(d, exist_ok=True)
    for n in os.listdir(d):
        if n.endswith(".json"):
            os.remove(os.path.join(d, n))


def build():
    with open(os.path.join(INDEX, "synonyms.json"), encoding="utf-8") as f:
        synonyms = json.load(f)
    phrases = phrase_list(synonyms)

    cases = {}
    bad = []
    if os.path.isdir(CASES):
        for folder in sorted(os.listdir(CASES)):
            fdir = os.path.join(CASES, folder)
            if not os.path.isdir(fdir):
                continue
            for name in sorted(os.listdir(fdir)):
                if name.startswith("."):
                    continue
                try:
                    cid, header = parse_case(os.path.join(fdir, name), folder, name)
                    cases[cid] = header
                except ValueError as e:
                    bad.append("FORMAT_ERROR %s/%s %s" % (folder, name, e))
    if bad:
        print("\n".join(bad))
        sys.exit(1)

    errors, words, titles = {}, {}, {}
    lists = {t: [] for t in TYPES}
    unconfirmed = []
    for cid, h in sorted(cases.items()):
        ctype = h["type"]
        if h["error"]:
            errors.setdefault(normalize_error(h["error"]), []).append(cid)
        text = " ".join([h["title"], h["keywords"], h["error"]])
        for term in normalize(text, phrases):
            words.setdefault(term[:2], {}).setdefault(term, []).append("%s:%s" % (cid, ctype))
        titles.setdefault(cid.split("/")[0], {})[cid] = {"title": h["title"], "type": ctype, "fix": h["fix"]}
        mark = "" if h["fix"] == "confirmed" else " [unconfirmed]"
        lists[ctype].append("%s %s%s" % (cid, h["title"], mark))
        if h["fix"] == "unconfirmed":
            unconfirmed.append("%s %s" % (cid, h["title"]))

    clear_generated("words")
    clear_generated("titles")
    write_json(os.path.join(INDEX, "errors.json"), errors)
    for prefix, data in words.items():
        write_json(os.path.join(INDEX, "words", prefix + ".json"), data)
    for folder, data in titles.items():
        write_json(os.path.join(INDEX, "titles", folder + ".json"), data)
    for t in TYPES:
        body = "# %s cases\n\nGenerated by scripts/build_index.py. Case ID then title.\n\n" % t
        body += "".join("- %s\n" % line for line in lists[t])
        with open(os.path.join(INDEX, t + ".md"), "w", encoding="utf-8") as f:
            f.write(body)
    body = ("# Unconfirmed fixes\n\nGenerated by scripts/build_index.py. Cases whose fix was not confirmed in the ticket.\n"
            "To confirm one, change its header line to fix: confirmed and push.\n\n")
    body += "".join("- %s\n" % line for line in unconfirmed)
    with open(os.path.join(INDEX, "unconfirmed.md"), "w", encoding="utf-8") as f:
        f.write(body)
    print("INDEX_OK %d" % len(cases))


def local_load(path):
    full = os.path.join(INDEX, path)
    if not os.path.isfile(full):
        return None
    with open(full, encoding="utf-8") as f:
        return json.load(f)


def run_tests():
    path = os.path.join(ROOT, "tests", "search-cases.tsv")
    failed = 0
    count = 0
    with open(path, encoding="utf-8") as f:
        rows = [l.rstrip("\n").split("\t") for l in f if l.strip()]
    for row in rows[1:]:
        row += [""] * (4 - len(row))
        query, type_, error, expect = row[:4]
        count += 1
        found = [p for p, _ in kbsearch.search(local_load, query, type_ or None, error or None)]
        if "cases/%s.md" % expect not in found:
            failed += 1
            print("TEST_FAILED %s | %s" % (expect, query))
    if failed:
        sys.exit(1)
    print("TESTS_OK %d" % count)


if __name__ == "__main__":
    build()
    run_tests()
